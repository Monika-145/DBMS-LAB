### 1. Key Value Pair Based

- Data is stored in key/value pairs.
- Each key is unique, and the value can be JSON, BLOB, or string.
- It is suitable for handling large amounts of data and heavy loads.
- Examples: Redis, Dynamo, Riak.

### 2. Column-Based

- Data is stored and managed in columns.
- Each column is treated separately.
- Provides high performance for aggregation queries such as SUM, COUNT, AVG, and MIN.
- Examples: HBase, Cassandra, Hypertable.

### 3. Document-Oriented

- Data is stored and retrieved as key-value pairs.
- The value is stored as a document in JSON or XML format.
- The database can understand and query the document.

### 4. Graph-Based

- Stores entities and the relationships between them.
- Entities are represented as nodes and relationships as edges.
- Every node and edge has a unique identifier.

